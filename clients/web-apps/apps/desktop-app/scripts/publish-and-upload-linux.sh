#!/usr/bin/env bash
# Publishes the AvintraDesktopApp (Tauri) Linux bundle and uploads it to the
# selected server(s).
#
# Usage:
#   ./publish-and-upload-linux.sh [--version <ver>] [--target-servers uat|prod|both]
#                                 [--mode both|publish|upload] [--dry-run]
#                                 [--no-sync-version] [--include-deb]
#
# What it builds (Linux):
#   - AppImage     (bundle/appimage/avintra-desktop-app_<version>_amd64.AppImage)
#     -> end-user install: chmod +x, double-click. No package manager needed.
#     (renamed to AvintraDesktopApp_<version>_amd64.AppImage on upload for a
#     friendlier name)
#   - .AppImage.sig -> generated by `npx tauri build` when
#     TAURI_SIGNING_PRIVATE_KEY is set (loaded from scripts/.env.local);
#     used by the in-app auto-updater on linux.
#   - deb (optional, --include-deb): bundle/deb/*.deb for apt-based distros.
#
# Defaults:
#   --version         reads version from src-tauri/tauri.conf.json
#   --target-servers  prompts interactively if not provided (1=uat, 2=prod, 3=both)
#   --dry-run         print the plan without building/uploading
#   --mode both       build and upload (default)
#   --mode publish    build only; do not upload
#   --mode upload     no build; upload the existing v<version> artifacts
#   --include-deb     also upload the .deb package
#   --no-sync-version skip the release-version.sh sync step
#
# Build prerequisites (Debian/Ubuntu):
#   libwebkit2gtk-4.1-dev libgtk-3-dev librsvg2-dev patchelf libfuse2
# (deb/rpm builds additionally need dpkg/rpmbuild; without them the script
# passes --bundles appimage so the build does not fail on missing tooling.)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DESKTOP_APP_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"              # apps/desktop-app
REPO_ROOT="$(cd "$DESKTOP_APP_DIR/../../../.." && pwd)"      # repo root
TAURI_CONF="$DESKTOP_APP_DIR/src-tauri/tauri.conf.json"
SECRETS_FILE="$DESKTOP_APP_DIR/scripts/.env.local"

VERSION=""
TARGET_SERVERS=""
MODE=""
DRY_RUN=false
INCLUDE_DEB=false
SYNC_VERSION=true

# --- Parse arguments -----------------------------------------------------------
while [[ $# -gt 0 ]]; do
  case "$1" in
    --version)
      VERSION="$2"
      shift 2
      ;;
    --target-servers)
      TARGET_SERVERS="$2"
      shift 2
      ;;
    --dry-run)
      DRY_RUN=true
      shift
      ;;
    --mode)
      MODE="$2"
      shift 2
      ;;
    --include-deb)
      INCLUDE_DEB=true
      shift
      ;;
    --no-sync-version)
      SYNC_VERSION=false
      shift
      ;;
    *)
      echo "error: unknown argument: $1" >&2
      echo "usage: $0 [--version <ver>] [--target-servers uat|prod|both] [--mode both|publish|upload] [--dry-run] [--include-deb] [--no-sync-version]" >&2
      exit 1
      ;;
  esac
done

# --- Load signing secrets --------------------------------------------------------
load_secrets() {
  if [[ ! -f "$SECRETS_FILE" ]]; then
    if [[ "$DRY_RUN" == true ]]; then
      echo "[dry-run] warning: $SECRETS_FILE not found; continuing (plan only)." >&2
      return 0
    fi
    echo "error: $SECRETS_FILE not found." >&2
    echo "Copy scripts/.env.local.example to scripts/.env.local and fill in TAURI_SIGNING_PRIVATE_KEY" >&2
    exit 1
  fi
  set -a
  # shellcheck disable=SC1090
  source "$SECRETS_FILE"
  set +a
  if [[ -z "${TAURI_SIGNING_PRIVATE_KEY:-}" && "$DRY_RUN" == false ]]; then
    echo "error: TAURI_SIGNING_PRIVATE_KEY is empty in $SECRETS_FILE" >&2
    exit 1
  fi
}

# --- Resolve version -----------------------------------------------------------
if [[ ! -f "$TAURI_CONF" ]]; then
  echo "error: tauri.conf.json not found at $TAURI_CONF" >&2
  exit 1
fi

if [[ -z "$VERSION" ]]; then
  VERSION="$(node -e "console.log(JSON.parse(require('fs').readFileSync('$TAURI_CONF','utf8')).version)")"
fi

if [[ -z "$VERSION" ]]; then
  echo "error: cannot determine version. Set \"version\" in src-tauri/tauri.conf.json or pass --version." >&2
  exit 1
fi

# --- Resolve operation mode -----------------------------------------------------
resolve_mode() {
  local choice="$1"
  case "$choice" in
    both|1)      echo "both" ;;
    publish|2)   echo "publish" ;;
    upload|3)    echo "upload" ;;
    *)           echo "error: unsupported mode: $choice (use both | publish | upload)" >&2; exit 1 ;;
  esac
}

if [[ -z "$MODE" ]]; then
  if [[ -t 0 ]]; then
    echo "Select operation mode:"
    echo "  1) publish and upload"
    echo "  2) publish only (no upload)"
    echo "  3) upload only (use existing artifacts, no build)"
    read -r -p "Enter 1-3 or name (both/publish/upload): " MODE
  else
    MODE="both"
  fi
fi

MODE="$(resolve_mode "$MODE")"

# --- Resolve target servers ----------------------------------------------------
resolve_servers() {
  local choice="$1"
  case "$choice" in
    uat|1)            echo "avuat.aventisia.com" ;;
    prod|2)           echo "avweb1.aventisia.com avweb2.aventisia.com" ;;
    both|3)           echo "avuat.aventisia.com avweb1.aventisia.com avweb2.aventisia.com" ;;
    *)                echo "error: unsupported server combination: $choice" >&2; exit 1 ;;
  esac
}

# Publish-only mode has no upload target, so server selection is skipped.
if [[ "$MODE" == "publish" ]]; then
  if [[ -n "$TARGET_SERVERS" ]]; then
    echo "note: --target-servers is ignored in publish-only mode (no upload)."
  fi
  SERVER_LIST=""
else
  if [[ -z "$TARGET_SERVERS" ]]; then
    if [[ -t 0 ]]; then
      echo "Select target server(s):"
      echo "  1) uat"
      echo "  2) prod"
      echo "  3) both (uat + prod)"
      read -r -p "Enter 1-3 or name (uat/prod/both): " TARGET_SERVERS
    else
      echo "error: --target-servers is required when running non-interactively" >&2
      exit 1
    fi
  fi

  SERVER_LIST="$(resolve_servers "$TARGET_SERVERS")"
fi

# --- Sync version from git tag ---------------------------------------------------
# Skipped in upload-only mode: it would rewrite version files for artifacts
# that were already built.
if [[ "$SYNC_VERSION" == true && "$DRY_RUN" == false && "$MODE" != "upload" ]]; then
  echo "Syncing release version from git tag into tauri.conf.json / package.json / Cargo.toml ..."
  "$REPO_ROOT/scripts/release-version.sh"
fi

# --- Build ----------------------------------------------------------------------
BUNDLE_DIR="$DESKTOP_APP_DIR/src-tauri/target/release/bundle"
APPIMAGE_DIR="$BUNDLE_DIR/appimage"
DEB_DIR="$BUNDLE_DIR/deb"

# Clean previous artifacts so stale files are never uploaded. Skipped in
# upload-only mode so existing build outputs can be re-used.
if [[ "$MODE" != "upload" ]]; then
  rm -rf "$APPIMAGE_DIR"
  rm -rf "$DEB_DIR"
fi

load_secrets

# If dpkg/rpmbuild tooling is missing, restrict bundles to AppImage so the
# build does not fail on distros without deb/rpm packaging support.
TAURI_BUNDLE_ARGS=()
if ! command -v dpkg-deb >/dev/null 2>&1; then
  TAURI_BUNDLE_ARGS=(--bundles appimage)
fi

BUILD_DESC="AppImage"
[[ "$INCLUDE_DEB" == true ]] && BUILD_DESC="AppImage + deb"

if [[ "$MODE" == "upload" ]]; then
  echo "Upload-only mode: skipping build, using existing artifacts for v$VERSION ..."
else
  echo "Building AvintraDesktopApp ($BUILD_DESC) v$VERSION ..."

  if [[ "$DRY_RUN" == true ]]; then
    echo "[dry-run] (cd $DESKTOP_APP_DIR && npx tauri build ${TAURI_BUNDLE_ARGS[*]:-})"
  else
    (cd "$DESKTOP_APP_DIR" && npx tauri build "${TAURI_BUNDLE_ARGS[@]:-}")
  fi
fi

# --- Collect artifacts -----------------------------------------------------------
# Upload-only mode matches the configured version explicitly so a stale build
# from a different version is never uploaded.
if [[ "$MODE" == "upload" ]]; then
  APPIMAGE_PATH="$(ls "$APPIMAGE_DIR"/*_"${VERSION}"_*.AppImage 2>/dev/null | head -n1 || true)"
  DEB_PATH="$(ls "$DEB_DIR"/*_"${VERSION}"_*.deb 2>/dev/null | head -n1 || true)"
else
  APPIMAGE_PATH="$(ls "$APPIMAGE_DIR"/*.AppImage 2>/dev/null | head -n1 || true)"
  DEB_PATH="$(ls "$DEB_DIR"/*.deb 2>/dev/null | head -n1 || true)"
fi
APPIMAGE_SIG="${APPIMAGE_PATH}.sig"

if [[ "$DRY_RUN" == true ]]; then
  APPIMAGE_PATH="$APPIMAGE_DIR/avintra-desktop-app_${VERSION}_amd64.AppImage"
  APPIMAGE_SIG="${APPIMAGE_PATH}.sig"
  echo "[dry-run] expected artifacts:"
  echo "[dry-run]   $APPIMAGE_PATH"
  echo "[dry-run]   $APPIMAGE_SIG"
  if [[ "$INCLUDE_DEB" == true ]]; then
    echo "[dry-run]   $DEB_DIR/avintra-desktop-app_${VERSION}_amd64.deb"
  fi
else
  if [[ -z "$APPIMAGE_PATH" ]]; then
    if [[ "$MODE" == "upload" ]]; then
      echo "error: no AppImage for v$VERSION found in $APPIMAGE_DIR. Build one first with --mode publish or both, or pass --version matching an existing build." >&2
    else
      echo "error: no AppImage found in $APPIMAGE_DIR after build." >&2
    fi
    exit 1
  fi
  if [[ ! -f "$APPIMAGE_SIG" ]]; then
    echo "error: updater signature not found: $APPIMAGE_SIG" >&2
    echo "hint: ensure createUpdaterArtifacts is true and TAURI_SIGNING_PRIVATE_KEY is set." >&2
    exit 1
  fi
fi

# Friendlier end-user name for the uploaded AppImage. The updater signature
# must sit next to the artifact under the SAME name, so the sig copy is renamed
# too: <name>.AppImage / <name>.AppImage.sig.
APPIMAGE_UPLOAD_NAME="AvintraDesktopApp_${VERSION}_linux-x64.AppImage"
APPIMAGE_UPLOAD_PATH="$(dirname "$APPIMAGE_PATH")/$APPIMAGE_UPLOAD_NAME"
APPIMAGE_SIG_UPLOAD_PATH="${APPIMAGE_UPLOAD_PATH}.sig"

echo "Built artifacts:"
if [[ "$DRY_RUN" == false ]]; then
  ls -lh "$APPIMAGE_PATH" "$APPIMAGE_SIG"
  [[ "$INCLUDE_DEB" == true && -f "$DEB_PATH" ]] && ls -lh "$DEB_PATH"
fi

# --- Upload -----------------------------------------------------------------------
if [[ "$MODE" == "publish" ]]; then
  echo "Upload skipped (mode: publish only)."
  exit 0
fi

REMOTE_DIR='/var/www/aventisia.com/files/binaries'

# Prepare the friendly-named copies (artifact + sig keep matching names).
if [[ "$DRY_RUN" == false ]]; then
  cp "$APPIMAGE_PATH" "$APPIMAGE_UPLOAD_PATH"
  cp "$APPIMAGE_SIG" "$APPIMAGE_SIG_UPLOAD_PATH"
fi

echo "Uploading to: $SERVER_LIST"
for server in $SERVER_LIST; do
  if [[ "$DRY_RUN" == true ]]; then
    echo "[dry-run] ssh admin@$server 'mkdir -p $REMOTE_DIR'"
    echo "[dry-run] scp $APPIMAGE_UPLOAD_PATH admin@$server:${REMOTE_DIR}/"
    echo "[dry-run] scp $APPIMAGE_SIG_UPLOAD_PATH admin@$server:${REMOTE_DIR}/"
    if [[ "$INCLUDE_DEB" == true ]]; then
      echo "[dry-run] scp $DEB_PATH admin@$server:${REMOTE_DIR}/"
    fi
  else
    echo "Uploading to $server ..."
    ssh "admin@$server" "mkdir -p $REMOTE_DIR"
    scp "$APPIMAGE_UPLOAD_PATH" "admin@$server:${REMOTE_DIR}/"
    scp "$APPIMAGE_SIG_UPLOAD_PATH" "admin@$server:${REMOTE_DIR}/"
    if [[ "$INCLUDE_DEB" == true ]]; then
      if [[ -n "$DEB_PATH" && -f "$DEB_PATH" ]]; then
        scp "$DEB_PATH" "admin@$server:${REMOTE_DIR}/"
      else
        echo "warning: --include-deb passed but no .deb found in $DEB_DIR; skipping deb upload." >&2
      fi
    fi
    echo "Successfully uploaded AvintraDesktopApp Linux to $server"
  fi
done

# Remove the friendly-named copies; the originals stay in the bundle dir.
if [[ "$DRY_RUN" == false ]]; then
  rm -f "$APPIMAGE_UPLOAD_PATH" "$APPIMAGE_SIG_UPLOAD_PATH"
fi