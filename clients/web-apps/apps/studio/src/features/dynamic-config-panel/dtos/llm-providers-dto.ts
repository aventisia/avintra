import { ActionTypesEnum } from "@/features/credits-management/constants/action-types-enum";
import { UsageSourceTypesEnum } from "@/features/credits-management/constants/usage-source-types-enum";

/**
 * Represents a literal provider type for LLM providers.
 */
export type ProviderLiteral = "openai" | "ollama" | "deepinfra" | "googlegemini";

/**
 * Represents the message structure for LLM chat models.
 */
export interface LLMMessageDto {
  /**
   * Role of the message sender.
   */
  role: "system" | "developer" | "user" | "assistant";

  /**
   * Content of the message.
   */
  content: string;
}

export interface ToolActionDto {
  action: string;
  approval: "auto" | "human";
}

export interface ToolConfigDto {
  tool: string;
  credential_name: string;
  actions: ToolActionDto[];
}

/**
 * Represents a request for generating an LLM response.
 */
export interface LLMRequestDto {
  /**
   * Provider of the LLM model.
   */
  provider: ProviderLiteral;

  /**
   * The model to be used for generation.
   */
  model: string;

  /**
   * Input content for the LLM model, either as a string or a list of messages.
   */
  input: string | LLMMessageDto[];

  /**
   * Optional list of base64-encoded files for OCR or text extraction.
   */
  files?: string[];

  /**
   * Indicates whether the output should be parsed as JSON.
   */
  is_json_output?: boolean;

  /**
   * Optional JSON schema to validate the response.
   */
  json_schema?: string | null;

  /**
   * Maximum number of tokens for the output.
   */
  max_output_tokens?: number | null;

  /**
   * Enables Bring Your Own Key (BYOK) support.
   */
  is_byok_enabled?: boolean;

  /**
   * Optional credential reference for BYOK. May hold a name or a legacy UUID.
   */
  credential_name?: string | null;

  /**
   * Temperature setting for the model.
   */
  temperature?: number;

  /**
   * Top-p setting for the model.
   */
  top_p?: number;

  /**
   * Reasoning effort for OpenAI reasoning models (e.g. o1/o3/gpt-5): low | medium | high.
   */
  reasoning_effort?: string | null;

  /**
   * Flag to indicate whether to stream the response.
   */
  stream?: boolean;

  /**
   * Optional tool/service configurations for tool-enabled agents.
   */
  tool_config?: ToolConfigDto[];

  /**
   * Gets or sets the reference type (e.g.Agent, Platform) associated with the usage.
   */
  ref_type: UsageSourceTypesEnum | string;

  /**
   * Gets or sets the unique identifier for the reference object.
   */
  ref_id: string;

  /**
   * Gets or sets the name of the reference object (e.g., my_new_agent).
   */
  ref_name: string;

  /**
   * Gets or sets the action type (e.g.AgentExecution) associated with the usage.
   */
  action: ActionTypesEnum | string;

  kb_names?: string[] | null;

  skill_names?: string[] | null;

  is_chat_agent?: boolean;

  generate_followup_messages?: boolean;
}

/**
 * Represents a chunked response for streaming LLM responses.
 */
export interface LLMChunkResponseDto {
  /**
   * Provider of the LLM model.
   */
  provider: ProviderLiteral;

  /**
   * Model used for generation.
   */
  model: string;

  /**
   * Chunk of the output generated by the LLM model.
   */
  output: string;
}

/**
 * Represents a full or final response from the LLM.
 */
export interface LLMResponseDto {
  /**
   * Provider of the LLM model.
   */
  provider: ProviderLiteral;

  /**
   * Model used for generating the response.
   */
  model: string;

  /**
   * Final output generated by the LLM model.
   */
  output: string;

  /**
   * Status of the response, like 'completed', 'failed', etc.
   */
  status?: "completed" | "failed" | "in_progress" | "cancelled" | "queued" | "incomplete";

  /**
   * Reason for the model's finish (e.g., stop token or time limit).
   */
  finishReason?: string;

  /**
   * Date and time when the response was created.
   */
  createdOn: string;

  /**
   * Maximum output tokens used in the response.
   */
  maxOutputTokens?: number;

  /**
   * Temperature used for generating the response.
   */
  temperature: number;

  /**
   * Top-p value used for the response generation.
   */
  top_p: number;

  /**
   * Indicates if the response was streamed.
   */
  stream: boolean;

  /**
   * Time taken to generate the response, in seconds.
   */
  timeTaken?: number;

  /**
   * Number of tokens used in the input.
   */
  inputTokens?: number;

  /**
   * Cached tokens used in the input.
   */
  inputCachedTokens?: number;

  /**
   * Number of tokens generated in the output.
   */
  outputTokens?: number;

  /**
   * Number of tokens used for reasoning in the output.
   */
  outputReasoningTokens?: number;

  /**
   * Flag to indicate if the output is expected to be in JSON format.
   */
  is_json_output?: boolean;

  /**
   * Flag to indicate if BYOK is enabled.
   */
  is_byok_enabled?: boolean;

  /**
   * Credential ID for BYOK (legacy).
   */
  credentialId?: string;

  /**
   * Credential name for BYOK.
   */
  credentialName?: string;

  /**
   * Any error message related to the response.
   */
  error?: string;
}
