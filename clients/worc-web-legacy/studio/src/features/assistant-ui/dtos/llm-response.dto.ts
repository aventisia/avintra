import { LLMProviderType } from "..";

/**
 * Generic object payload returned by tools/functions.
 */
export type LLMToolPayload = Record<string, unknown>;

/**
 * Function/tool call output item.
 */
export interface LLMToolsOutputDto {
  type: string;

  call_id: string;

  output: {
    agentId?: string;
    agentName?: string;
    provider?: string;
    action?: string;
    credentialId?: string;

    /**
     * Dynamic payload returned by tool execution.
     * Can contain any object shape.
     */
    payload?: LLMToolPayload;

    /**
     * Allow additional dynamic fields.
     */
    [key: string]: unknown;
  };
}

/**
 * Supported output types from LLM.
 */
export type LLMOutputDto = {
  text?: string;
  tools?: LLMToolsOutputDto[];
  recommended_actions: string[];
};

/**
 * Represents a full or final response from the LLM.
 */
export interface LLMResponseDto {
  /**
   * Provider of the LLM model.
   */
  provider: LLMProviderType;

  /**
   * Model used for generating the response.
   */
  model: string;

  /**
   * Final output generated by the LLM model.
   *
   * Can be:
   * - plain text
   * - tool outputs
   * - generic JSON object
   */
  output: LLMOutputDto;

  /**
   * Status of the response, like 'completed', 'failed', etc.
   */
  status?:
    | "completed"
    | "failed"
    | "in_progress"
    | "cancelled"
    | "queued"
    | "incomplete";

  /**
   * Reason for the model's finish (e.g., stop token or time limit).
   */
  finishReason?: string;

  /**
   * Date and time when the response was created.
   */
  createdOn: string;

  /**
   * Maximum output tokens used in the response.
   */
  maxOutputTokens?: number;

  /**
   * Temperature used for generating the response.
   */
  temperature: number;

  /**
   * Top-p value used for the response generation.
   */
  top_p: number;

  /**
   * Indicates if the response was streamed.
   */
  stream: boolean;

  /**
   * Time taken to generate the response, in seconds.
   */
  timeTaken?: number;

  /**
   * Number of tokens used in the input.
   */
  inputTokens?: number;

  /**
   * Cached tokens used in the input.
   */
  inputCachedTokens?: number;

  /**
   * Number of tokens generated in the output.
   */
  outputTokens?: number;

  /**
   * Number of tokens used for reasoning in the output.
   */
  outputReasoningTokens?: number;

  /**
   * Flag to indicate if the output is expected to be in JSON format.
   */
  is_json_output?: boolean;

  /**
   * Flag to indicate if BYOK is enabled.
   */
  is_byok_enabled?: boolean;

  /**
   * Credential ID for BYOK.
   */
  credentialId?: string;

  /**
   * Any error message related to the response.
   */
  error?: string;
}
