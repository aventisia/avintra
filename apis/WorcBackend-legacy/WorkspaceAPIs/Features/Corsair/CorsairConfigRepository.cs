namespace WorkspaceAPIs.Features.Corsair;

using AspNetToolkit.Config;

/// <summary>
/// Loads the generated Corsair config files
/// (<c>&lt;UploadDirectory&gt;/config/corsair/&lt;Plugin&gt;/&lt;Action&gt;Connector.json</c>)
/// and the separate <c>CorsairActionMap.json</c> that maps node names to the
/// exact sidecar invocation metadata.
///
/// The config files are the single source of truth for the node schema shown in
/// Studio. The action map is the single source of truth for the dotted sidecar
/// operation, so the backend never reconstructs it from a display name.
///
/// Corsair configs are generated by the Corsair sidecar into a dedicated shared
/// path under the files directory (<c>&lt;UploadDirectory&gt;/config/corsair</c>),
/// keeping them out of the Workspace API codebase so a Corsair change does not
/// force a main app rebuild. For local dev, the repository falls back to the
/// codebase ConfigFiles folder when the shared path is absent.
/// </summary>
public class CorsairConfigRepository
{
    private readonly ILogger<CorsairConfigRepository> _logger;
    private readonly IWebHostEnvironment _env;
    private readonly AppDefaultConfig _appDefaultConfig;
    private readonly Dictionary<string, CorsairConnectorConfig> _configCache = new(StringComparer.OrdinalIgnoreCase);
    private readonly Dictionary<string, CorsairActionInvocation> _invocationCache = new(StringComparer.OrdinalIgnoreCase);
    private readonly object _gate = new();

    public CorsairConfigRepository(
        ILogger<CorsairConfigRepository> logger,
        IWebHostEnvironment env,
        AppDefaultConfig appDefaultConfig)
    {
        _logger = logger;
        _env = env;
        _appDefaultConfig = appDefaultConfig;
    }

    /// <summary>
    /// Resolves a Corsair config by plugin + action.
    /// <paramref name="action"/> is the PascalCase action segment used in the
    /// node name (e.g. "ApiIssuesList"); the file is named
    /// <c>&lt;Action&gt;Connector.json</c> under the plugin folder.
    /// </summary>
    public CorsairConnectorConfig? GetConfig(string plugin, string action)
    {
        if (string.IsNullOrWhiteSpace(plugin) || string.IsNullOrWhiteSpace(action))
        {
            return null;
        }
        var key = $"{plugin}/{action}";
        lock (_gate)
        {
            if (_configCache.TryGetValue(key, out var cached))
            {
                return cached;
            }
        }

        var path = ResolveConfigPath(plugin, action);
        if (path == null || !System.IO.File.Exists(path))
        {
            _logger.LogWarning("Corsair config not found for '{Plugin}/{Action}' (path {Path}).",
                plugin, action, path);
            return null;
        }

        try
        {
            // Read outside the lock to avoid blocking concurrent lookups during file I/O.
            var json = System.IO.File.ReadAllText(path);
            var config = System.Text.Json.JsonSerializer.Deserialize<CorsairConnectorConfig>(
                json, new JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            if (config == null)
            {
                return null;
            }
            lock (_gate)
            {
                _configCache[key] = config;
            }
            return config;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair config '{Plugin}/{Action}'.", plugin, action);
            return null;
        }
    }

    /// <summary>
    /// Resolves the dotted sidecar action and invocation metadata for a node name.
    /// <paramref name="nodeName"/> is the full Studio node name, e.g.
    /// "Corsair/Github/ApiIssuesListConnector".
    /// </summary>
    public CorsairActionInvocation? GetInvocation(string nodeName)
    {
        if (string.IsNullOrWhiteSpace(nodeName))
        {
            return null;
        }

        lock (_gate)
        {
            if (_invocationCache.TryGetValue(nodeName, out var cached))
            {
                return cached;
            }
        }

        var mapPath = ResolveActionMapPath();
        if (mapPath == null || !System.IO.File.Exists(mapPath))
        {
            _logger.LogWarning("Corsair action map not found at {Path}.", mapPath);
            return null;
        }

        try
        {
            // Read outside the lock to avoid blocking concurrent lookups during file I/O.
            var json = System.IO.File.ReadAllText(mapPath);
            var map = System.Text.Json.JsonSerializer.Deserialize<List<CorsairActionInvocation>>(
                json, new JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            if (map == null)
            {
                return null;
            }

            var invocation = map.FirstOrDefault(i =>
                string.Equals(i.NodeName, nodeName, StringComparison.OrdinalIgnoreCase));
            if (invocation == null)
            {
                _logger.LogWarning("No Corsair invocation metadata found for node '{NodeName}'.", nodeName);
                return null;
            }

            lock (_gate)
            {
                _invocationCache[nodeName] = invocation;
            }
            return invocation;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair action map.");
            return null;
        }
    }

    public string? GetPluginIdForVaultType(string vaultType)
    {
        if (string.IsNullOrWhiteSpace(vaultType))
        {
            return null;
        }

        var configRoot = ResolveConfigRoot();
        var mapPath = ResolveArtifactPath(configRoot, "CorsairVaultTypeToPluginId.json");
        if (mapPath == null)
        {
            return null;
        }

        try
        {
            var map = System.Text.Json.JsonSerializer.Deserialize<Dictionary<string, string>>(
                File.ReadAllText(mapPath),
                new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            return map?.GetValueOrDefault(vaultType);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair vault type map at {Path}.", mapPath);
            return null;
        }
    }

    public IReadOnlyList<string> GetPluginIdsForVaultType(string vaultType)
    {
        if (string.IsNullOrWhiteSpace(vaultType))
        {
            return Array.Empty<string>();
        }

        var configRoot = ResolveConfigRoot();
        var catalogPath = ResolveArtifactPath(configRoot, "CorsairIntegrationCatalog.json");
        if (catalogPath == null)
        {
            return Array.Empty<string>();
        }

        try
        {
            var catalog = System.Text.Json.JsonSerializer.Deserialize<List<CorsairIntegrationCatalogEntry>>(
                File.ReadAllText(catalogPath),
                new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            return catalog?
                .Where(entry => string.Equals(entry.VaultType, vaultType, StringComparison.OrdinalIgnoreCase))
                .Select(entry => entry.PluginId)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .OrderBy(plugin => plugin, StringComparer.OrdinalIgnoreCase)
                .ToArray() ?? Array.Empty<string>();
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair integration catalog at {Path}.", catalogPath);
            return Array.Empty<string>();
        }
    }

    private static string? ResolveArtifactPath(string configRoot, string fileName)
    {
        var candidates = new[]
        {
            Path.Combine(configRoot, fileName),
            Path.Combine(Directory.GetParent(configRoot)?.FullName ?? configRoot, fileName),
        };

        return candidates.FirstOrDefault(File.Exists);
    }

    private sealed class CorsairIntegrationCatalogEntry
    {
        public string PluginId { get; set; } = string.Empty;
        public string VaultType { get; set; } = string.Empty;
    }

    /// <summary>
    /// Resolves the Corsair config root. Prefers the dedicated shared path
    /// (<c>&lt;UploadDirectory&gt;/config/corsair</c>) written by the Corsair
    /// sidecar; falls back to the codebase ConfigFiles folder for local dev.
    /// </summary>
    private string ResolveConfigRoot()
    {
        var sharedRoot = ResolveSharedConfigRoot();
        if (sharedRoot != null && System.IO.Directory.Exists(sharedRoot))
        {
            return sharedRoot;
        }

        // Local dev fallback: the generator writes to the codebase ConfigFiles
        // folder when CORSAIR_CONFIG_DIR is not set.
        try
        {
            return Path.Combine(_env.ContentRootPath, "Features", "CloudConnectors", "ConfigFiles", "Corsair");
        }
        catch
        {
            return Path.Combine(AppContext.BaseDirectory, "Features", "CloudConnectors", "ConfigFiles", "Corsair");
        }
    }

    /// <summary>
    /// Resolves the dedicated shared Corsair config root from the configured
    /// upload directory (<c>&lt;UploadDirectory&gt;/config/corsair</c>), or
    /// <c>null</c> when the upload directory is not configured.
    /// </summary>
    private string? ResolveSharedConfigRoot()
    {
        var uploadDir = _appDefaultConfig?.FileUploadConfig?.UploadDirectory;
        if (string.IsNullOrWhiteSpace(uploadDir))
        {
            return null;
        }
        return Path.Combine(uploadDir, "config", "corsair");
    }

    private string? ResolveConfigPath(string plugin, string action)
    {
        var root = ResolveConfigRoot();
        var pluginDir = char.ToUpperInvariant(plugin[0]) + plugin[1..];
        // The generated file is named "<Action>Connector.json" (Cloud Connector convention).
        var actionSegment = action.EndsWith("Connector", StringComparison.OrdinalIgnoreCase)
            ? action
            : action + "Connector";
        return Path.Combine(root, pluginDir, $"{actionSegment}.json");
    }

    private string? ResolveActionMapPath()
    {
        var root = ResolveConfigRoot();
        return Path.Combine(root, "CorsairActionMap.json");
    }
}
