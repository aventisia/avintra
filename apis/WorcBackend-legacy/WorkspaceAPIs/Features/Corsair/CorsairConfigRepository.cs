namespace WorkspaceAPIs.Features.Corsair;

/// <summary>
/// Loads the generated Corsair config files
/// (<c>Features/CloudConnectors/ConfigFiles/Corsair/&lt;Plugin&gt;/&lt;Action&gt;Connector.json</c>)
/// and the separate <c>CorsairActionMap.json</c> that maps node names to the
/// exact sidecar invocation metadata.
///
/// The config files are the single source of truth for the node schema shown in
/// Studio. The action map is the single source of truth for the dotted sidecar
/// operation, so the backend never reconstructs it from a display name.
///
/// The thousands of per-plugin config files are generated by the Corsair sidecar
/// and deployed to a shared server path derived from the configured upload
/// directory (<c>AppDefaultConfig:FileUploadConfig:UploadDirectory</c> →
/// <c>.../files/configs/Corsair</c>) so they do not bloat the codebase. During
/// local development (or when the server path is absent) they fall back to the
/// Workspace API codebase ConfigFiles folder. The small sibling artifacts
/// (action map, integration catalog, vault-type map) always live in the codebase
/// ConfigFiles folder and are committed.
/// </summary>
public class CorsairConfigRepository
{
    private readonly ILogger<CorsairConfigRepository> _logger;
    private readonly IWebHostEnvironment _env;
    private readonly IConfiguration _configuration;
    private readonly AppDefaultConfig _appDefaultConfig;
    private readonly Dictionary<string, CorsairConnectorConfig> _configCache = new(StringComparer.OrdinalIgnoreCase);
    private readonly Dictionary<string, CorsairActionInvocation> _invocationCache = new(StringComparer.OrdinalIgnoreCase);
    private readonly object _gate = new();

    public CorsairConfigRepository(
        ILogger<CorsairConfigRepository> logger,
        IWebHostEnvironment env,
        IConfiguration configuration,
        AppDefaultConfig appDefaultConfig)
    {
        _logger = logger;
        _env = env;
        _configuration = configuration;
        _appDefaultConfig = appDefaultConfig;
    }

    /// <summary>
    /// Resolves a Corsair config by plugin + action.
    /// <paramref name="action"/> is the PascalCase action segment used in the
    /// node name (e.g. "ApiIssuesList"); the file is named
    /// <c>&lt;Action&gt;Connector.json</c> under the plugin folder.
    /// </summary>
    public CorsairConnectorConfig? GetConfig(string plugin, string action)
    {
        if (string.IsNullOrWhiteSpace(plugin) || string.IsNullOrWhiteSpace(action))
        {
            return null;
        }
        var key = $"{plugin}/{action}";
        lock (_gate)
        {
            if (_configCache.TryGetValue(key, out var cached))
            {
                return cached;
            }
        }

        var path = ResolveConfigPath(plugin, action);
        if (path == null || !System.IO.File.Exists(path))
        {
            _logger.LogWarning("Corsair config not found for '{Plugin}/{Action}' (path {Path}).",
                plugin, action, path);
            return null;
        }

        try
        {
            // Read outside the lock to avoid blocking concurrent lookups during file I/O.
            var json = System.IO.File.ReadAllText(path);
            var config = System.Text.Json.JsonSerializer.Deserialize<CorsairConnectorConfig>(
                json, new JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            if (config == null)
            {
                return null;
            }
            lock (_gate)
            {
                _configCache[key] = config;
            }
            return config;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair config '{Plugin}/{Action}'.", plugin, action);
            return null;
        }
    }

    /// <summary>
    /// Resolves the dotted sidecar action and invocation metadata for a node name.
    /// <paramref name="nodeName"/> is the full Studio node name, e.g.
    /// "Corsair/Github/ApiIssuesListConnector".
    /// </summary>
    public CorsairActionInvocation? GetInvocation(string nodeName)
    {
        if (string.IsNullOrWhiteSpace(nodeName))
        {
            return null;
        }

        lock (_gate)
        {
            if (_invocationCache.TryGetValue(nodeName, out var cached))
            {
                return cached;
            }
        }

        var mapPath = ResolveActionMapPath();
        if (mapPath == null || !System.IO.File.Exists(mapPath))
        {
            _logger.LogWarning("Corsair action map not found at {Path}.", mapPath);
            return null;
        }

        try
        {
            // Read outside the lock to avoid blocking concurrent lookups during file I/O.
            var json = System.IO.File.ReadAllText(mapPath);
            var map = System.Text.Json.JsonSerializer.Deserialize<List<CorsairActionInvocation>>(
                json, new JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            if (map == null)
            {
                return null;
            }

            var invocation = map.FirstOrDefault(i =>
                string.Equals(i.NodeName, nodeName, StringComparison.OrdinalIgnoreCase));
            if (invocation == null)
            {
                _logger.LogWarning("No Corsair invocation metadata found for node '{NodeName}'.", nodeName);
                return null;
            }

            lock (_gate)
            {
                _invocationCache[nodeName] = invocation;
            }
            return invocation;
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair action map.");
            return null;
        }
    }

    public string? GetPluginIdForVaultType(string vaultType)
    {
        if (string.IsNullOrWhiteSpace(vaultType))
        {
            return null;
        }

        vaultType = NormalizeVaultType(vaultType);

        var mapPath = ResolveArtifactPath("CorsairVaultTypeToPluginId.json");
        if (mapPath == null)
        {
            return null;
        }

        try
        {
            var map = System.Text.Json.JsonSerializer.Deserialize<Dictionary<string, string>>(
                File.ReadAllText(mapPath),
                new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            return map?.GetValueOrDefault(vaultType);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair vault type map at {Path}.", mapPath);
            return null;
        }
    }

    public IReadOnlyList<string> GetPluginIdsForVaultType(string vaultType)
    {
        if (string.IsNullOrWhiteSpace(vaultType))
        {
            return Array.Empty<string>();
        }

        vaultType = NormalizeVaultType(vaultType);

        var catalogPath = ResolveArtifactPath("CorsairIntegrationCatalog.json");
        if (catalogPath == null)
        {
            return Array.Empty<string>();
        }

        try
        {
            var catalog = System.Text.Json.JsonSerializer.Deserialize<List<CorsairIntegrationCatalogEntry>>(
                File.ReadAllText(catalogPath),
                new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            return catalog?
                .Where(entry => string.Equals(entry.VaultType, vaultType, StringComparison.OrdinalIgnoreCase))
                .Select(entry => entry.PluginId)
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .OrderBy(plugin => plugin, StringComparer.OrdinalIgnoreCase)
                .ToArray() ?? Array.Empty<string>();
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair integration catalog at {Path}.", catalogPath);
            return Array.Empty<string>();
        }
    }

    /// <summary>
    /// Resolves the vault type for a Corsair plugin id, if any. Used to filter
    /// credentials to the type a platform tool can be invoked with.
    /// </summary>
    public string? GetVaultTypeForPluginId(string pluginId)
    {
        if (string.IsNullOrWhiteSpace(pluginId))
        {
            return null;
        }

        var catalogPath = ResolveArtifactPath("CorsairIntegrationCatalog.json");
        if (catalogPath == null)
        {
            return null;
        }

        try
        {
            var catalog = System.Text.Json.JsonSerializer.Deserialize<List<CorsairIntegrationCatalogEntry>>(
                File.ReadAllText(catalogPath),
                new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            return catalog?
                .Where(entry => string.Equals(entry.PluginId, pluginId, StringComparison.OrdinalIgnoreCase))
                .Select(entry => entry.VaultType)
                .FirstOrDefault(vaultType => !string.IsNullOrWhiteSpace(vaultType));
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair integration catalog at {Path}.", catalogPath);
            return null;
        }
    }

    private static string NormalizeVaultType(string vaultType) => vaultType.Trim() switch
    {
        "Teams" or "Onedrive" or "Sharepoint" => "M365",
        _ => vaultType.Trim(),
    };

    /// <summary>
    /// Resolves a sibling artifact (action map, integration catalog, vault-type
    /// map) from the codebase ConfigFiles root. These small files are committed
    /// and always live in the codebase, regardless of where the per-plugin
    /// configs are deployed.
    /// </summary>
    private string? ResolveArtifactPath(string fileName)
    {
        // Sibling artifacts (action map, integration catalog, vault‑type map) are
        // always present in the codebase ConfigFiles folder, but during local
        // development we also want to serve them from the same server‑side
        // Corsair root used for per‑plugin configs when that root is
        // configured. This mirrors the behaviour added to the controller for
        // the per‑plugin files.
        var codebaseRoot = ResolveCodebaseConfigRoot();
        var corsairRoot = ResolveConfigRoot(); // may be server path or fallback

        var candidates = new List<string>
        {
            // Prefer the server‑side location if it exists.
            Path.Combine(corsairRoot, fileName),
            // Fallback to the codebase location.
            Path.Combine(codebaseRoot, fileName),
            // Also check the parent of the codebase root (historical fallback).
            Path.Combine(Directory.GetParent(codebaseRoot)?.FullName ?? codebaseRoot, fileName),
        };

        return candidates.FirstOrDefault(File.Exists);
    }

    /// <summary>
    /// Resolves the OAuth-capable plugin id for a vault type, if any. Used as a dynamic
    /// fallback so newly generated OAuth plugins do not require a hardcoded mapping.
    /// </summary>
    public string? GetOAuthPluginIdForVaultType(string vaultType)
    {
        if (string.IsNullOrWhiteSpace(vaultType))
        {
            return null;
        }

        vaultType = NormalizeVaultType(vaultType);

        var catalogPath = ResolveArtifactPath("CorsairIntegrationCatalog.json");
        if (catalogPath == null)
        {
            return null;
        }

        try
        {
            var catalog = System.Text.Json.JsonSerializer.Deserialize<List<CorsairIntegrationCatalogEntry>>(
                File.ReadAllText(catalogPath),
                new System.Text.Json.JsonSerializerOptions { PropertyNameCaseInsensitive = true });
            return catalog?
                .Where(entry => string.Equals(entry.VaultType, vaultType, StringComparison.OrdinalIgnoreCase)
                    && string.Equals(entry.DefaultAuthMode, "oauth_2", StringComparison.OrdinalIgnoreCase))
                .Select(entry => entry.PluginId)
                .OrderBy(id => id, StringComparer.OrdinalIgnoreCase)
                .FirstOrDefault();
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Failed to parse Corsair integration catalog at {Path}.", catalogPath);
            return null;
        }
    }

    private sealed class CorsairIntegrationCatalogEntry
    {
        public string PluginId { get; set; } = string.Empty;
        public string VaultType { get; set; } = string.Empty;
        public string DefaultAuthMode { get; set; } = string.Empty;
    }

    /// <summary>
    /// Resolves the Corsair config root for the per-plugin config files. On the
    /// server this is the shared path derived from the configured upload
    /// directory (<c>AppDefaultConfig:FileUploadConfig:UploadDirectory</c>, e.g.
    /// <c>/var/www/aventisia.com/files</c> → <c>.../files/configs/Corsair</c>).
    /// When that path is not configured or does not exist (local development),
    /// it falls back to the codebase ConfigFiles folder so every dev uses the
    /// same committed configs.
    /// </summary>
    private string ResolveConfigRoot()
    {
        var configured = _configuration["Corsair:ConfigRoot"];
        if (!string.IsNullOrWhiteSpace(configured) && Directory.Exists(configured))
        {
            return Path.GetFullPath(configured);
        }

        // Derive the server path from the shared upload directory instead of
        // hardcoding it, so the Corsair configs live alongside the other
        // deployed files under the same root.
        var uploadDirectory = _appDefaultConfig.FileUploadConfig.UploadDirectory;
        if (!string.IsNullOrWhiteSpace(uploadDirectory))
        {
            var derived = Path.Combine(uploadDirectory, "configs", "Corsair");
            if (Directory.Exists(derived))
            {
                return Path.GetFullPath(derived);
            }
        }

        return ResolveCodebaseConfigRoot();
    }

    /// <summary>
    /// Resolves the codebase ConfigFiles/Corsair folder, which is the local-dev
    /// source of the per-plugin configs and the home of the committed sibling
    /// artifacts.
    /// </summary>
    private string ResolveCodebaseConfigRoot()
    {
        try
        {
            return Path.Combine(_env.ContentRootPath, "Features", "CloudConnectors", "ConfigFiles", "Corsair");
        }
        catch
        {
            return Path.Combine(AppContext.BaseDirectory, "Features", "CloudConnectors", "ConfigFiles", "Corsair");
        }
    }

    private string? ResolveConfigPath(string plugin, string action)
    {
        var root = ResolveConfigRoot();
        var pluginDir = char.ToUpperInvariant(plugin[0]) + plugin[1..];
        // The generated file is named "<Action>Connector.json" (Cloud Connector convention).
        var actionSegment = action.EndsWith("Connector", StringComparison.OrdinalIgnoreCase)
            ? action
            : action + "Connector";
        return Path.Combine(root, pluginDir, $"{actionSegment}.json");
    }

    private string? ResolveActionMapPath()
    {
        // The generator writes CorsairActionMap.json directly under the ConfigFiles
        // root (sibling of the Corsair/ plugin folder), not inside the Corsair/
        // subfolder. It is a committed sibling artifact, so it always resolves from
        // the codebase ConfigFiles root.
        var codebaseRoot = ResolveCodebaseConfigRoot();
        var parent = Path.GetDirectoryName(codebaseRoot);
        return parent == null ? null : Path.Combine(parent, "CorsairActionMap.json");
    }
}
