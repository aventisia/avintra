[Route("cloud-connector/config-file")]
[ApiController]
[Authorize]
public class CloudConnectorsConfigFilesController : ControllerBase
{
    private readonly IWebHostEnvironment _env;
    private readonly AspNetToolkit.Config.AppDefaultConfig _appDefaultConfig;

    public CloudConnectorsConfigFilesController(
        IWebHostEnvironment env,
        AspNetToolkit.Config.AppDefaultConfig appDefaultConfig)
    {
        _env = env;
        _appDefaultConfig = appDefaultConfig;
    }

    [HttpGet("{*filePath}")]
    public IActionResult GetConfigFile(string filePath)
    {
        // Corsair configs are generated by the Corsair sidecar into a dedicated
        // shared path (<UploadDirectory>/config/corsair) so they stay out of the
        // Workspace API codebase. Serve them from there when present; otherwise
        // fall back to the codebase ConfigFiles folder (local dev).
        //
        // All other configs (Camel, in-house connectors, and the global Cloud
        // Connector mapping) are owned by the Workspace API and stay in the
        // codebase ConfigFiles folder — they are unaffected by this branch.
        var corsairSharedRoot = ResolveCorsairSharedRoot();
        if (corsairSharedRoot != null &&
            filePath?.StartsWith("Corsair", StringComparison.OrdinalIgnoreCase) == true)
        {
            var corsairFullPath = Path.GetFullPath(Path.Combine(corsairSharedRoot, filePath ?? ""));
            if (corsairFullPath.StartsWith(corsairSharedRoot) && System.IO.File.Exists(corsairFullPath))
            {
                return PhysicalFile(corsairFullPath, GetContentType(filePath));
            }
        }

        var root = Path.Combine(_env.ContentRootPath, "Features", "CloudConnectors", "ConfigFiles");
        var fullPath = Path.GetFullPath(Path.Combine(root, filePath ?? ""));
        if (!fullPath.StartsWith(root) || !System.IO.File.Exists(fullPath))
            return NotFound();

        return PhysicalFile(fullPath, GetContentType(filePath));
    }

    private string? ResolveCorsairSharedRoot()
    {
        var uploadDir = _appDefaultConfig?.FileUploadConfig?.UploadDirectory;
        if (string.IsNullOrWhiteSpace(uploadDir))
        {
            return null;
        }
        return Path.Combine(uploadDir, "config", "corsair");
    }

    private static string GetContentType(string? filePath)
    {
        return filePath?.EndsWith(".json", StringComparison.OrdinalIgnoreCase) == true
            ? "application/json"
            : "application/octet-stream";
    }
}
