namespace AspNetToolkit.DTOs;

/// <summary>
/// Represents the response schema for an LLM full response or the last chunk in a streaming response.
/// This schema includes various properties related to the LLM provider's response, including model output,
/// status, tokens, temperature, and error information.
/// </summary>
public class LLMResponse
{
    /// <summary>
    /// Gets or sets the LLM provider (e.g., OpenAI, Ollama, etc.).
    /// </summary>
    public string Provider { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the model name used for the LLM request (e.g., "gpt-4").
    /// </summary>
    public string Model { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the output generated by the LLM.
    /// </summary>
    public object Output { get; set; } = new object();

    /// <summary>
    /// Gets or sets the status of the LLM response (e.g., "completed", "failed", "in_progress", etc.).
    /// </summary>
    public string Status { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the reason for finishing the LLM response (e.g., "timeout", "max tokens", etc.).
    /// </summary>
    public string FinishReason { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the timestamp when the response was created.
    /// </summary>
    public DateTime CreatedOn { get; set; } = DateTime.UtcNow;

    /// <summary>
    /// Gets or sets the maximum number of tokens allowed in the model output.
    /// </summary>
    public int? MaxOutputTokens { get; set; }

    /// <summary>
    /// Gets or sets the temperature setting for the LLM's randomness (between 0 and 1).
    /// </summary>
    public float Temperature { get; set; }

    /// <summary>
    /// Gets or sets the top-p (nucleus sampling) value for the LLM response generation.
    /// </summary>
    public float TopP { get; set; }

    /// <summary>
    /// Gets or sets a value indicating whether the response is streamed.
    /// </summary>
    public bool Stream { get; set; }

    /// <summary>
    /// Gets or sets the total time taken to process the LLM response.
    /// </summary>
    public float TimeTaken { get; set; }

    /// <summary>
    /// Gets or sets the number of input tokens used in the LLM request.
    /// </summary>
    public int InputTokens { get; set; }

    /// <summary>
    /// Gets or sets the number of input tokens that were cached.
    /// </summary>
    public int InputCachedTokens { get; set; }

    /// <summary>
    /// Gets or sets the number of output tokens generated by the LLM.
    /// </summary>
    public int OutputTokens { get; set; }

    /// <summary>
    /// Gets or sets the number of reasoning tokens generated by the LLM in the output.
    /// </summary>
    public int OutputReasoningTokens { get; set; }

    /// <summary>
    /// Gets or sets a value indicating whether the model output should be in JSON format.
    /// </summary>
    public bool IsJsonOutput { get; set; }

    /// <summary>
    /// Gets or sets a value indicating whether BYOK (Bring Your Own Key) support is enabled.
    /// </summary>
    public bool IsByokEnabled { get; set; }

    /// <summary>
    /// Gets or sets the credential NAME for BYOK (Bring Your Own Key) support.
    /// </summary>
    public string? CredentialName { get; set; }

    /// <summary>
    /// Gets or sets any error message associated with the LLM response.
    /// </summary>
    public string Error { get; set; } = string.Empty;
}