public class ConversationHistoryDto
{
    /// <summary>
    /// Gets or sets the unique identifier for the conversation history entry.
    /// </summary>
    public Guid Id { get; set; }

    /// <summary>
    /// Gets or sets the role/type of the participant in the conversation (e.g., User, Bot, Automation).
    /// </summary>
    [Required]
    public ParticipantTypesEnum ParticipantType { get; set; }

    /// <summary>
    /// Gets or sets the name of the participant in the conversation.
    /// </summary>
    [Required]
    public string? ParticipantName { get; set; }

    /// <summary>
    /// Gets or sets the unique identifier of the participant in the conversation.
    /// </summary>
    public string? ParticipantId { get; set; }

    /// <summary>
    /// Gets or sets the content of the message, with a maximum length of 4000 characters.
    /// </summary>
    [Required]
    public string Message { get; set; } = string.Empty;

    /// <summary>
    /// Indicates whether the message was sent by a user (true) or generated by the system/model (false).
    /// </summary>
    public bool IsUserMessage { get; set; }

    /// <summary>
    /// Gets or sets the UTC timestamp when the message was created.
    /// </summary>
    public DateTime Timestamp { get; set; } = DateTime.UtcNow;

    /// <summary>
    /// Gets or sets an optional identifier used to group messages within the same conversation session.
    /// </summary>
    public Guid? ConversationId { get; set; }

    /// <summary>
    /// Gets or sets the name of the ML model that interacted with or generated the message.
    /// </summary>
    public string? MLModelName { get; set; }

    /// <summary>
    /// Gets or sets the unique identifier of the ML model that generated or interacted with the message.
    /// </summary>
    [Required]
    public Guid MLModelId { get; set; }
}
