namespace AccountsAPIs.DTOs;

/// <summary>
/// Represents the data required to create a new order.
/// </summary>
public class OrderRequestDto
{
    /// <summary>
    /// Gets or sets the total amount for the order in the selected currency (INR, USD, etc.).
    /// </summary>
    /// <remarks>
    /// The amount provided here should be in the selected currency (rupees or dollars).
    /// The value is necessary to process the order and should be specified in the chosen currency.
    /// </remarks>
    public required decimal Amount { get; set; }

    /// <summary>
    /// Gets or sets the currency for the order.
    /// </summary>
    /// <remarks>
    /// The currency value should be a valid type from the <see cref="CurrencyTypesEnum"/> enum.
    /// </remarks>
    public required CurrencyTypesEnum Currency { get; set; }

    /// <summary>
    /// Gets or sets an optional receipt identifier associated with the order.
    /// </summary>
    /// <remarks>
    /// If provided, this value helps link the order to a specific transaction or reference.
    /// This field is optional.
    /// </remarks>
    public string? Receipt { get; set; }
}

/// <summary>
/// Represents the data returned after an order has been successfully created.
/// </summary>
public class OrderResponseDto
{
    /// <summary>
    /// Gets or sets the unique identifier for the created order.
    /// </summary>
    /// <remarks>
    /// The order ID is generated by the system after the order is processed, serving as a unique reference.
    /// </remarks>
    public string Id { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the total amount for the order in the selected currency (INR, USD, etc.).
    /// </summary>
    /// <remarks>
    /// The amount in the response is returned in the selected currency (rupees or dollars), 
    /// matching the amount provided in the request.
    /// </remarks>
    public decimal Amount { get; set; }

    /// <summary>
    /// Gets or sets the currency used for the order.
    /// </summary>
    /// <remarks>
    /// The currency indicates the denomination in which the order amount is specified.
    /// It is represented by a value from the <see cref="CurrencyTypesEnum"/> enum (e.g., "INR", "USD").
    /// </remarks>
    public CurrencyTypesEnum Currency { get; set; }

    /// <summary>
    /// Gets or sets the receipt identifier associated with the order.
    /// </summary>
    /// <remarks>
    /// This is an optional field. It helps track or reference the order and is returned if provided during order creation.
    /// </remarks>
    public string? Receipt { get; set; }

    /// <summary>
    /// Gets or sets the current status of the order.
    /// </summary>
    /// <remarks>
    /// The status reflects the current state of the order, such as "pending", "completed", or "failed".
    /// </remarks>
    public string? Status { get; set; }
}
